const DICTIONARIES: Record<Lang, Record<string, string>> = { en, ar }

export type TParams = Record<string, string | number>

function interpolate(template: string, params?: TParams): string {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  )
}

const pluralRules: Record<Lang, Intl.PluralRules> = {
  en: new Intl.PluralRules(LOCALES.en),
  ar: new Intl.PluralRules('ar'),
}

const numberFormats: Record<Lang, Intl.NumberFormat> = {
  en: new Intl.NumberFormat(LOCALES.en),
  ar: new Intl.NumberFormat(LOCALES.ar),
}

export function translate(lang: Lang, key: TKey, params?: TParams): string {
  return interpolate(DICTIONARIES[lang][key] ?? en[key], params)
}

/** Translates a pluralised string; `{n}` is replaced with the formatted count. */
export function translatePlural(lang: Lang, base: TPluralKey, count: number, params?: TParams): string {
  const dictionary = DICTIONARIES[lang]
  const category = pluralRules[lang].select(count)
  const template = dictionary[`${base}.${category}`] ?? dictionary[`${base}.other`] ?? en[`${base}.other` as TKey]
  return interpolate(template, { ...params, n: numberFormats[lang].format(count) })
}
